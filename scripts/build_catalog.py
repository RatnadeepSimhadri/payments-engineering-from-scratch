#!/usr/bin/env python3
"""Derive catalog.json, the README Contents section, and ROADMAP.md from curriculum.json.

Usage:
    python3 scripts/build_catalog.py            # rewrite README Contents + ROADMAP.md, print summary
    python3 scripts/build_catalog.py --check    # exit 1 if README/ROADMAP are stale
    python3 scripts/build_catalog.py --json     # print catalog.json to stdout

The README section between <!-- CONTENTS:START --> and <!-- CONTENTS:END --> and the
badges between <!-- COUNTS:START --> and <!-- COUNTS:END --> are generated. Everything
else in README.md is hand-written. ROADMAP.md is fully generated.
"""

from __future__ import annotations

import argparse
import json
import re
import sys

from _lib import (
    ROOT,
    iter_lessons,
    lesson_dir,
    lesson_languages,
    lesson_status,
    load_curriculum,
    load_languages,
    minutes_to_hours,
)

STATUS_GLYPH = {"Complete": "✅", "In Progress": "🚧", "Planned": "⬚"}


def build_catalog() -> dict:
    curriculum = load_curriculum()
    phases = []
    for phase in curriculum["phases"]:
        lessons = []
        for lesson in phase["lessons"]:
            path = lesson_dir(phase, lesson)
            langs = [l["name"] for l in lesson_languages(path)]
            status = lesson_status(path, lesson["type"])
            lessons.append(
                {
                    **lesson,
                    "path": path.relative_to(ROOT).as_posix(),
                    "languages": langs,
                    "status": status,
                }
            )
        phases.append({**phase, "lessons": lessons, "minutes": sum(l["minutes"] for l in lessons)})
    complete = sum(1 for p in phases for l in p["lessons"] if l["status"] == "Complete")
    total = sum(len(p["lessons"]) for p in phases)
    return {
        "title": curriculum["title"],
        "tagline": curriculum["tagline"],
        "tracks": curriculum["tracks"],
        "languages": [l["name"] for l in load_languages(ci_only=True)],
        "lessonCount": total,
        "completeCount": complete,
        "phaseCount": len(phases),
        "totalMinutes": sum(p["minutes"] for p in phases),
        "phases": phases,
    }


def render_contents(catalog: dict) -> str:
    out = ["<!-- CONTENTS:START -->", "", "## Contents", ""]
    out.append(
        f"{catalog['phaseCount']} phases, {catalog['lessonCount']} lessons, three tracks. "
        "Click a phase to expand its lesson list. `Lang` lists the languages whose from-scratch "
        "implementation already exists; planned lessons show a dash."
    )
    out.append("")
    for track in catalog["tracks"]:
        out.append(f"### {track['title']}")
        out.append("")
        for phase in catalog["phases"]:
            if phase["number"] not in track["phases"]:
                continue
            done = sum(1 for l in phase["lessons"] if l["status"] == "Complete")
            out.append(f'<details id="phase-{phase["number"]}">')
            out.append(
                f'<summary><b>Phase {phase["number"]} — {phase["title"]}</b> &nbsp;'
                f'<code>{len(phase["lessons"])} lessons · {done} complete</code>&nbsp; '
                f'<em>{phase["motto"]}</em></summary>'
            )
            out.append("<br/>")
            out.append("")
            out.append("| # | Lesson | Type | Lang | Status |")
            out.append("|:---:|--------|:----:|------|:------:|")
            for lesson in phase["lessons"]:
                lang = ", ".join(lesson["languages"]) or "—"
                glyph = STATUS_GLYPH[lesson["status"]]
                out.append(
                    f'| {lesson["n"]:02d} | [{lesson["title"]}]({lesson["path"]}/) '
                    f'| {lesson["type"]} | {lang} | {glyph} |'
                )
            out.append("")
            out.append("</details>")
            out.append("")
    out.append("<!-- CONTENTS:END -->")
    return "\n".join(out)


def render_counts(catalog: dict) -> str:
    hours = catalog["totalMinutes"] // 60
    langs = ", ".join(catalog["languages"])
    return (
        "<!-- COUNTS:START -->\n"
        f"> {catalog['lessonCount']} lessons. {catalog['phaseCount']} phases. "
        f"3 tracks. {langs}. ~{hours} hours of guided building.\n"
        "<!-- COUNTS:END -->"
    )


def render_roadmap(catalog: dict) -> str:
    out = [
        "# Roadmap",
        "",
        "Status tracker for every phase and lesson. Generated by `scripts/build_catalog.py` from",
        "`curriculum/curriculum.json` and the lesson directories on disk; edit those, not this file.",
        "",
        f"Total estimated time: ~{catalog['totalMinutes'] // 60} hours, at your own pace. "
        f"{catalog['completeCount']} of {catalog['lessonCount']} lessons are complete.",
        "",
        "**Legend:** ✅ Complete (docs, quiz, and code in every CI language) &nbsp;·&nbsp; "
        "🚧 In Progress &nbsp;·&nbsp; ⬚ Planned",
        "",
        "A planned lesson has a title, a hook, and a time estimate in `curriculum.json`. Pick one,",
        "run `python3 scripts/scaffold_lesson.py <phase> <lesson>`, and follow `AGENTS.md`.",
        "",
    ]
    for phase in catalog["phases"]:
        done = sum(1 for l in phase["lessons"] if l["status"] == "Complete")
        glyph = "✅" if done == len(phase["lessons"]) else ("🚧" if done else "⬚")
        out.append(
            f"## Phase {phase['number']}: {phase['title']} — {glyph} (~{phase['minutes'] / 60:.0f} hours)"
        )
        out.append("")
        out.append("| # | Lesson | Status | Est. |")
        out.append("|---|--------|--------|------|")
        for lesson in phase["lessons"]:
            out.append(
                f"| {lesson['n']:02d} | {lesson['title']} | {STATUS_GLYPH[lesson['status']]} "
                f"| ~{lesson['minutes']} min |"
            )
        out.append("")
    return "\n".join(out)


def splice(text: str, start: str, end: str, replacement: str) -> str:
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f"README.md is missing the {start} … {end} markers")
    return pattern.sub(lambda _: replacement, text, count=1)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    catalog = build_catalog()
    if args.json:
        print(json.dumps(catalog, indent=2))
        return 0

    readme_path = ROOT / "README.md"
    roadmap_path = ROOT / "ROADMAP.md"
    readme = readme_path.read_text(encoding="utf-8")
    new_readme = splice(readme, "<!-- CONTENTS:START -->", "<!-- CONTENTS:END -->", render_contents(catalog))
    new_readme = splice(new_readme, "<!-- COUNTS:START -->", "<!-- COUNTS:END -->", render_counts(catalog))
    new_roadmap = render_roadmap(catalog)
    old_roadmap = roadmap_path.read_text(encoding="utf-8") if roadmap_path.exists() else ""

    stale = new_readme != readme or new_roadmap != old_roadmap
    if args.check:
        if stale:
            print("README.md or ROADMAP.md is stale; run python3 scripts/build_catalog.py")
            return 1
        print("README.md and ROADMAP.md are in sync")
        return 0

    readme_path.write_text(new_readme, encoding="utf-8")
    roadmap_path.write_text(new_roadmap, encoding="utf-8")
    (ROOT / "catalog.json").write_text(json.dumps(catalog, indent=2) + "\n", encoding="utf-8")
    write_phase_readmes(catalog)
    print(
        f"{catalog['lessonCount']} lessons across {catalog['phaseCount']} phases; "
        f"{catalog['completeCount']} complete; README.md, ROADMAP.md, catalog.json rewritten"
    )
    return 0



def render_phase_readme(phase: dict, catalog: dict) -> str:
    first = next((l for l in phase["lessons"] if l["status"] == "Complete"), phase["lessons"][0])
    first_cmd = ""
    if first.get("languages"):
        first_cmd = (
            "Run the first complete lesson from the repository root:\n\n```bash\n"
            f"python3 scripts/run_lesson.py {first['path']} --lang java\n```\n\n"
            "Keep the command, the exit code, and the test count as your first piece of evidence.\n"
        )
    done = sum(1 for l in phase["lessons"] if l["status"] == "Complete")
    out = [
        f"# Phase {phase['number']}: {phase['title']}",
        "",
        f"> {phase['motto']}",
        "",
        f"{len(phase['lessons'])} lessons, {done} complete, ~{phase['minutes'] // 60} hours. "
        "Generated from `curriculum/curriculum.json` by `scripts/build_catalog.py`.",
        "",
        "## Start this phase",
        "",
        f"**First lesson:** [{first['title']}]({first['slug']}/)",
        "",
        first_cmd,
        "With an agent tutor: `/learn` (Claude Code), `learn` (Codex), or `Use learn to teach the next lesson.` "
        "The tutor reads your language from `LEARNING.md`.",
        "",
        "## Lessons",
        "",
        "| # | Lesson | Type | Time | Hook |",
        "|:---:|--------|:----:|:----:|------|",
    ]
    for l in phase["lessons"]:
        # Authoring status lives in ROADMAP.md; a column of identical ticks here only reads like progress.
        flag = "" if l["status"] == "Complete" else f" {STATUS_GLYPH[l['status']]} *{l['status']}*"
        out.append(f"| {l['n']:02d} | [{l['title']}]({l['slug']}/){flag} | {l['type']} | ~{l['minutes']} min | {l['hook']} |")
    out += ["", "Browse the [full curriculum](../../README.md#contents) or the status [roadmap](../../ROADMAP.md)."]
    return "\n".join(out) + "\n"


def write_phase_readmes(catalog: dict) -> None:
    for phase in catalog["phases"]:
        folder = ROOT / "phases" / phase["slug"]
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "README.md").write_text(render_phase_readme(phase, catalog), encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
